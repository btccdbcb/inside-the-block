def write_design(design_dir: Path, alloc: Allocation, seed: int | None = None, extra: dict | None = None) -> dict:
    design_dir = Path(design_dir)
    tpath = design_dir / "targets.json"
    targets = json.loads(tpath.read_text())["targets"]
    if seed is None:
        seed = secrets.randbits(63)
    rows = generate(targets, alloc, seed)
    dpath = design_dir / "design.jsonl"
    dpath.write_bytes(("\n".join(dumps_row(r) for r in rows) + "\n").encode())
    campaign = {
        "study": "inside-the-block",
        "genesis_hash": "5eykt4UsFv8P8NJdTREpY1vzqKqZKvdpKuc147dw2N9d",
        "cap_lamports": 30_000_000,
        "sweep_to": "AwBiUwz1qUzkfKA5nAUu4uYEXz1vpKGvLjRAz6KvWtUn",
        "funder": "AET41ewiRXWPYRnSupUrYKaq51zUrKHJnq3FcCCkJ3Li",
        "campaign_end_utc": "2026-11-03T23:59:00Z",
        "sessions": SESSIONS,
        "carry_unfired_to": "D",
        # 8 payers (D-023): rent-exempt minimum 890,880 + 1,000,000 float; refilled below 890,880 + 300,000
        "payer_float_lamports": 1_890_880,
        "payer_low_lamports": 1_190_880,
        "batch_quads": 25,
        "generator_version": GENERATOR_VERSION,
        "seed": seed,
        "allocation": {"per_target": alloc.per_target, "per_extended": alloc.per_extended, "fill": alloc.fill,
                       "rows_by_target": {t["slot"]: rows_by_session(t, alloc.per_extended if t.get("extended")
                                                                     else alloc.per_target, alloc.fill)
                                          for t in targets},
                       "pilot_per_target": alloc.pilot_per_target, "pilot_extended": alloc.pilot_extended,
                       "smoke_targets": list(alloc.smoke_targets), "smoke_per_target": alloc.smoke_per_target},
        "rows": len(rows),
        "design_sha256": sha256_file(dpath),
        "targets_sha256": sha256_file(tpath),
        "prereg_sha256": "",
    }
    if extra:
        campaign.update(extra)
    (design_dir / "campaign.json").write_bytes((json.dumps(campaign, indent=2) + "\n").encode())
    return campaign


PAIR_MEMBERS = {"R": ("HI", "LO"), "R_IND": ("HI", "LO"), "C1": ("A", "B"), "C2": ("Q", "P"), "C3": ("Z", "X"),
                "EQ": ("A", "A"), "V_EQ": ("A1", "A"), "V_HI": ("HI1", "LO")}


def campaign_fees(rows) -> dict[str, int]:
    """Sum of every campaign probe's fee (5,000 per signature + priority fee) at each fee scale, with the designed
    control types (the v1 arm kept): the worst case the campaign sub-budget must hold."""
    from .verify import LAMPORTS_PER_SIGNATURE, SCALE, planned

    out = {}
    for scale in SCALE:
        out[scale] = sum(LAMPORTS_PER_SIGNATURE + planned(p, scale)["priority_fee"]
                         for r in rows if r["session"] in ("A", "B", "C", "D")
                         for t in (r["main_type"], r["control_type"]) for p in PAIR_MEMBERS[t])
    return out


def balance_table(rows):
    """Counts per target x tau and per target x main type for the campaign sessions (freeze check)."""
    import pandas as pd

    df = pd.DataFrame([r for r in rows if r["session"] in ("A", "B", "C", "D")])
    return {
        "target_x_tau": pd.crosstab(df.target_slot, df.tau_ms),
        "target_x_main": pd.crosstab(df.target_slot, df.main_type),
        "session_x_tau": pd.crosstab(df.session, df.tau_ms),
    }
