"""Design generator: every planned quad with its randomised factors, written before any live probe.

Output (LF only, deterministic given the seed):
  design/design.jsonl   one row per planned quad (smoke, pilot, A-D)
  design/campaign.json  sessions, caps, sweep address, allocation, seed, sha256 of design.jsonl and targets.json

The seed comes from the OS entropy pool and is recorded, so the design can be regenerated byte for byte.

Randomisation (EXPERIMENT_DESIGN): per target, the campaign's rows get exactly balanced margins for the send offset
tau (from the first shred of slot0 - 1, D-023), the main pair type, the gap dt inside races and the control pair; the
factors are paired up at random. Rows are then dealt to sessions by systematic allocation within each tau level, so
every session also sees every tau level in proportion. Within a target the firing order inside a session is random
(seq).
"""

from __future__ import annotations

import hashlib
import json
import secrets
from dataclasses import dataclass, field
from pathlib import Path

import numpy as np

TAU_LEVELS = [-300, -150, 0, 100, 200, 300, 400, 550, 700, 900]
MAIN_TYPES = {"R": 0.50, "C1": 0.15, "C2": 0.15, "C3": 0.10, "R_IND": 0.10}
RACE_DT = [0, 2, 10, 25, 50, 100]
CONTRAST_DT = [0, 1]
CONTROL_TYPES = {"EQ": 0.85, "V_EQ": 0.10, "V_HI": 0.05}
CONTROL_GAPS = [0, 10]
RACES = ("R", "R_IND")

GENERATOR_VERSION = 2


@dataclass
class Allocation:
    """Planned quads per core target per session, and per extended target per session.

    A target with few leader turns gets fewer: at most `fill` x its expected turns in the session window
    (turns_per_day from targets.json), so the runner can place every row with room for skips and retries.
    """

    per_target: dict[str, int] = field(default_factory=lambda: {"A": 23, "B": 23, "C": 19, "D": 12})
    per_extended: dict[str, int] = field(default_factory=lambda: {"A": 4, "B": 4, "C": 4, "D": 3})
    fill: float = 0.6
    pilot_per_target: int = 3
    pilot_extended: int = 1
    smoke_targets: tuple[str, ...] = ("T2", "T6")
    smoke_per_target: int = 2


def balanced(levels, weights, n, rng):
    """n draws with margins as close to `weights` as integers allow (largest remainder), in random order."""
    w = np.asarray(weights, dtype=float)
    w = w / w.sum()
    base = np.floor(w * n).astype(int)
    rem = n - base.sum()
    if rem:
        frac = w * n - base
        # ties broken at random so no level is systematically favoured
        order = np.lexsort((rng.random(len(w)), -frac))
        base[order[:rem]] += 1
    out = [lv for lv, k in zip(levels, base, strict=True) for _ in range(k)]
    rng.shuffle(out)
    return out


def even(levels, n, rng):
    return balanced(levels, [1.0] * len(levels), n, rng)


def systematic_split(items, sizes, rng):
    """Deal `items` (already ordered by stratum) into bins of the given sizes, proportionally within every stratum.

    Each bin's n slots sit at evenly spaced positions (j + u) / n on [0, 1) with its own random phase u; all slots
    are merged by position and the items are dealt in that order. Any run of consecutive items (one stratum) then
    gets every bin in proportion to its size, within one item.
    """
    total = sum(sizes.values())
    assert total == len(items)
    slots = []
    for k, n in sizes.items():
        u = rng.random()
        slots += [((j + u) / n, rng.random(), k) for j in range(n)]
    slots.sort()
    out = {k: [] for k in sizes}
    for it, (_, _, k) in zip(items, slots, strict=True):
        out[k].append(it)
    return out


def target_rows(target, n_by_session, rng):
    """Rows for one target over the campaign sessions (dict session -> n)."""
    n = sum(n_by_session.values())
    taus = even(TAU_LEVELS, n, rng)
    mains = balanced(list(MAIN_TYPES), list(MAIN_TYPES.values()), n, rng)
    n_race = sum(m in RACES for m in mains)
    race_dts = iter(even(RACE_DT, n_race, rng))
    contrast_dts = iter(even(CONTRAST_DT, n - n_race, rng))
    contrast_first = iter(even(["pref", "other"], n - n_race, rng))
    race_zero_first = iter(even(["pref", "other"], n, rng))
    controls = balanced(list(CONTROL_TYPES), list(CONTROL_TYPES.values()), n, rng)
    gaps = even(CONTROL_GAPS, n, rng)
    cfirst = even(["pref", "other"], n, rng)
    rows = []
    for i in range(n):
        m = mains[i]
        if m in RACES:
            dt = next(race_dts)
            # races: the low-priority member goes first and the high one follows after dt; at dt = 0 the order is random
            first = "other" if dt > 0 else next(race_zero_first)
        else:
            dt = next(contrast_dts)
            first = next(contrast_first)
        rows.append({
            "target_slot": target, "tau_ms": taus[i], "main_type": m, "dt_ms": dt, "main_first": first,
            "control_type": controls[i], "control_gap_ms": gaps[i], "control_first": cfirst[i],
            "payer_perm": [int(x) for x in rng.permutation(4)],
        })
    # stratify the session split by tau: order by tau (random within level), then deal systematically
    order = sorted(range(n), key=lambda i: (rows[i]["tau_ms"], rng.random()))
    split = systematic_split([rows[i] for i in order], n_by_session, rng)
    return split


def pilot_rows(target, n, rng):
    """Pilot: fee scale s1 and s10 both present, v1 controls in most quads, tau and main type spread."""
    scales = ["s1", "s10"] + even(["s1", "s10"], max(n - 2, 0), rng)
    scales = scales[:n]
    rng.shuffle(scales)
    taus = [int(x) for x in rng.choice(TAU_LEVELS, size=n, replace=False)]
    mains = [str(x) for x in rng.choice(list(MAIN_TYPES), size=n, p=list(MAIN_TYPES.values()))]
    controls = (["V_EQ", "V_HI"] + ["EQ"] * n)[:n] if n >= 2 else ["V_EQ"]
    rng.shuffle(controls)
    rows = []
    for i in range(n):
        m = mains[i]
        dt = int(rng.choice(RACE_DT)) if m in RACES else int(rng.choice(CONTRAST_DT))
        first = "other" if (m in RACES and dt > 0) else str(rng.choice(["pref", "other"]))
        rows.append({
            "target_slot": target, "tau_ms": taus[i], "main_type": m, "dt_ms": dt, "main_first": first,
            "control_type": controls[i], "control_gap_ms": int(rng.choice(CONTROL_GAPS)),
            "control_first": str(rng.choice(["pref", "other"])), "payer_perm": [int(x) for x in rng.permutation(4)],
            "fee_scale": scales[i],
        })
    return rows


def session_hours(sessions=None):
    """Window length in hours per session id."""
    out = {}
    for w in sessions or SESSIONS:
        h0, m0 = map(int, w["start_utc"].split(":"))
        h1, m1 = map(int, w["end_utc"].split(":"))
        out[w["id"]] = ((h1 * 60 + m1) - (h0 * 60 + m0)) % (24 * 60) / 60
    return out


def rows_by_session(target: dict, base: dict[str, int], fill: float) -> dict[str, int]:
    """Base allocation, capped at `fill` x the target's expected turns in each session window."""
    tpd = target.get("turns_per_day")
    if tpd is None:
        return dict(base)
    hours = session_hours()
    return {s: min(n, int(fill * tpd * hours[s] / 24)) for s, n in base.items()}


def generate(targets: list[dict], alloc: Allocation, seed: int):
    rng = np.random.default_rng(seed)
    by_slot = {t["slot"]: t for t in targets}
    core = [t["slot"] for t in targets if not t.get("extended")]
    ext = [t["slot"] for t in targets if t.get("extended")]
    out = []

    def emit(session, rows):
        order = rng.permutation(len(rows))
        for seq, i in enumerate(order):
            r = rows[i]
            r = {"quad_id": "", "session": session, **r, "seq": seq}
            out.append(r)

    smoke = []
    for t in alloc.smoke_targets:
        for _ in range(alloc.smoke_per_target):
            smoke.append({"target_slot": t, "tau_ms": 300, "main_type": "R", "dt_ms": 10, "main_first": "other",
                          "control_type": "EQ", "control_gap_ms": 0, "control_first": "pref",
                          "payer_perm": [int(x) for x in rng.permutation(4)], "fee_scale": "s1"})
    emit("smoke", smoke)
    pilot = []
    for t in core:
        pilot += pilot_rows(t, alloc.pilot_per_target, rng)
    for t in ext:
        pilot += pilot_rows(t, alloc.pilot_extended, rng)
    emit("pilot", pilot)
    per_session = {s: [] for s in alloc.per_target}
    for t in core:
        for s, rows in target_rows(t, rows_by_session(by_slot[t], alloc.per_target, alloc.fill), rng).items():
            per_session[s] += rows
    for t in ext:
        for s, rows in target_rows(t, rows_by_session(by_slot[t], alloc.per_extended, alloc.fill), rng).items():
            per_session[s] += rows
    for s, rows in per_session.items():
        emit(s, rows)
    # stable, readable ids: session-target-index in firing order
    counters: dict[tuple[str, str], int] = {}
    out.sort(key=lambda r: (["smoke", "pilot", *alloc.per_target].index(r["session"]), r["seq"]))
    for r in out:
        k = (r["session"], r["target_slot"])
        counters[k] = counters.get(k, 0) + 1
        r["quad_id"] = f"{r['session']}-{r['target_slot']}-{counters[k]:03d}"
    return out


FIELD_ORDER = ["quad_id", "session", "target_slot", "seq", "tau_ms", "main_type", "dt_ms", "main_first",
               "control_type", "control_gap_ms", "control_first", "payer_perm", "fee_scale"]


def dumps_row(r):
    return json.dumps({k: r[k] for k in FIELD_ORDER if k in r}, separators=(",", ":"))


def sha256_file(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


