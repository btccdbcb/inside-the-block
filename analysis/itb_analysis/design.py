def write_design(design_dir: Path, alloc: Allocation, seed: int | None = None, extra: dict | None = None) -> dict:
    design_dir = Path(design_dir)
    tpath = design_dir / "targets.json"
    targets = json.loads(tpath.read_text())["targets"]
    if seed is None:
        seed = secrets.randbits(63)
    rows = generate(targets, alloc, seed)
    dpath = design_dir / "design.jsonl"
    dpath.write_bytes(("\n".join(dumps_row(r) for r in rows) + "\n").encode())
    campaign = {
        "study": "inside-the-block",
        "genesis_hash": "5eykt4UsFv8P8NJdTREpY1vzqKqZKvdpKuc147dw2N9d",
        "cap_lamports": 30_000_000,
        "sweep_to": "AwBiUwz1qUzkfKA5nAUu4uYEXz1vpKGvLjRAz6KvWtUn",
        "funder": "AET41ewiRXWPYRnSupUrYKaq51zUrKHJnq3FcCCkJ3Li",
        "campaign_end_utc": "2026-11-03T23:59:00Z",
        "sessions": SESSIONS,
        "carry_unfired_to": "D",
        "payer_float_lamports": 1_400_000,
        "batch_quads": 25,
        "generator_version": GENERATOR_VERSION,
        "seed": seed,
        "allocation": {"per_target": alloc.per_target, "per_extended": alloc.per_extended,
                       "pilot_per_target": alloc.pilot_per_target, "pilot_extended": alloc.pilot_extended,
                       "smoke_targets": list(alloc.smoke_targets), "smoke_per_target": alloc.smoke_per_target},
        "rows": len(rows),
        "design_sha256": sha256_file(dpath),
        "targets_sha256": sha256_file(tpath),
        "prereg_sha256": "",
    }
    if extra:
        campaign.update(extra)
    (design_dir / "campaign.json").write_bytes((json.dumps(campaign, indent=2) + "\n").encode())
    return campaign


def balance_table(rows):
    """Counts per target x phi and per target x main type for the campaign sessions (freeze check)."""
    import pandas as pd

    df = pd.DataFrame([r for r in rows if r["session"] in ("A", "B", "C", "D")])
    return {
        "target_x_phi": pd.crosstab(df.target_slot, df.phi_ms),
        "target_x_main": pd.crosstab(df.target_slot, df.main_type),
        "session_x_phi": pd.crosstab(df.session, df.phi_ms),
    }
